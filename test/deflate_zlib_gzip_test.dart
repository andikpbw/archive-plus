import 'dart:convert';
import 'dart:math';
import 'dart:typed_data';

import 'package:archive_plus/archive_plus.dart';
import 'package:test/test.dart';

Uint8List _pseudoRandom(int length, [int seed = 42]) {
  final rng = Random(seed);
  return Uint8List.fromList(
    List<int>.generate(length, (_) => rng.nextInt(256)),
  );
}

void main() {
  final payloads = <String, Uint8List>{
    'empty': Uint8List(0),
    'single_byte': Uint8List.fromList(<int>[0x5a]),
    'two_bytes': Uint8List.fromList(<int>[0x00, 0xff]),
    'short_text': utf8.encode('Hello ArchivePlus! Modern compression in Dart.'),
    'repetitive_zeros_100k': Uint8List(100000),
    'all_256_bytes_repeated': Uint8List.fromList(
      List<int>.generate(16384, (i) => i & 0xff),
    ),
    'english_prose_80k': utf8.encode(
      'ArchivePlus is a modern, lightweight, zero-dependency archive library. ' *
          1200,
    ),
    'incompressible_random_75k': _pseudoRandom(75000, 1337),
    'mixed_blocks_180k': Uint8List.fromList(<int>[
      ...utf8.encode('Structured JSON log entry {"ok":true,"id":123}\n' * 1500),
      ..._pseudoRandom(50000, 99),
      ...List<int>.filled(60000, 0x41),
    ]),
  };

  group('DEFLATE (RFC 1951)', () {
    for (final level in CompressionLevel.values) {
      test('round-trips all payloads at level ${level.name}', () {
        for (final entry in payloads.entries) {
          final compressed = ArchivePlus.deflate(entry.value, level: level);
          final restored = ArchivePlus.inflate(
            compressed,
            securityPolicy: ArchiveSecurityPolicy.unrestricted,
          );
          expect(restored, equals(entry.value), reason: entry.key);
        }
      });
    }

    test(
      'incompressible random data does not bloat beyond stored overhead',
      () {
        final randomData = _pseudoRandom(40000, 777);
        final compressed = ArchivePlus.deflate(randomData);
        // Stored block overhead is only ~5 bytes per 64 KiB block.
        expect(compressed.length, lessThan(randomData.length + 32));
        expect(ArchivePlus.inflate(compressed), equals(randomData));
      },
    );

    test('rejects invalid DEFLATE block type 3 and corrupted stored NLEN', () {
      // BFINAL=1, BTYPE=3 => 0b00000111 = 0x07
      expect(
        () => ArchivePlus.inflate(Uint8List.fromList(<int>[0x07])),
        throwsA(isA<ArchiveFormatException>()),
      );
      // BFINAL=1, BTYPE=0, LEN=5, bad NLEN=0
      expect(
        () => ArchivePlus.inflate(
          Uint8List.fromList(<int>[
            0x01,
            0x05,
            0x00,
            0x00,
            0x00,
            1,
            2,
            3,
            4,
            5,
          ]),
        ),
        throwsA(isA<ArchiveFormatException>()),
      );
    });
  });

  group('ZLIB (RFC 1950)', () {
    for (final level in CompressionLevel.values) {
      test('round-trips all payloads at level ${level.name}', () {
        for (final entry in payloads.entries) {
          final compressed = ArchivePlus.zlib(
            entry.value,
            options: ZLibOptions(level: level),
          );
          final restored = ArchivePlus.unzlib(
            compressed,
            options: const ZLibOptions(
              securityPolicy: ArchiveSecurityPolicy.unrestricted,
            ),
          );
          expect(restored, equals(entry.value), reason: entry.key);
        }
      });
    }

    test('detects Adler-32 checksum tampering', () {
      final z = ArchivePlus.zlib(utf8.encode('Check my Adler-32 trailer!'));
      z[z.length - 1] ^= 0xff;
      expect(
        () => ArchivePlus.unzlib(z),
        throwsA(isA<ArchiveChecksumException>()),
      );
    });

    test('supports dart:convert Stream transformation', () async {
      final source = utf8.encode('Streaming ZLIB chunk test! ' * 500);
      const codec = ZLibPlusCodec();
      final chunks = <List<int>>[
        source.sublist(0, 1000),
        source.sublist(1000, 5000),
        source.sublist(5000),
      ];
      final compressedChunks = await Stream<List<int>>.fromIterable(
        chunks,
      ).transform(codec.encoder).toList();
      final decodedChunks = await Stream<List<int>>.fromIterable(
        compressedChunks,
      ).transform(codec.decoder).toList();
      final restored = decodedChunks.expand((c) => c).toList();
      expect(restored, equals(source));
    });
  });

  group('GZIP (RFC 1952)', () {
    test('round-trips with full header metadata and FHCRC', () {
      final mtime = DateTime.utc(2026, 11, 21, 10, 30, 0);
      final data = utf8.encode('GZIP header metadata verification ' * 200);
      final gz = ArchivePlus.gzip(
        data,
        options: GZipOptions(
          level: CompressionLevel.best,
          filename: 'report.txt',
          comment: 'Generated by ArchivePlus',
          modifiedTime: mtime,
          extra: const <int>[0x41, 0x50, 0x02, 0x00, 0x01, 0x02],
          includeHeaderCrc: true,
        ),
      );

      final result = ArchivePlus.gunzipWithMetadata(gz);
      expect(result.bytes, equals(data));
      expect(result.metadata.filename, 'report.txt');
      expect(result.metadata.comment, 'Generated by ArchivePlus');
      expect(result.metadata.modifiedTime, mtime);
      expect(
        result.metadata.extra,
        equals(<int>[0x41, 0x50, 0x02, 0x00, 0x01, 0x02]),
      );
    });

    test('decodes concatenated multi-member GZIP streams', () {
      final part1 = ArchivePlus.gzip(utf8.encode('First member. '));
      final part2 = ArchivePlus.gzip(utf8.encode('Second member. '));
      final part3 = ArchivePlus.gzip(utf8.encode('Third member!'));
      final combined = Uint8List.fromList(<int>[...part1, ...part2, ...part3]);

      final decoded = ArchivePlus.gunzip(combined);
      expect(
        utf8.decode(decoded),
        'First member. Second member. Third member!',
      );
    });

    test('detects CRC-32 and ISIZE tampering', () {
      final gz = ArchivePlus.gzip(utf8.encode('Tamper test payload'));
      final badCrc = Uint8List.fromList(gz)..[gz.length - 6] ^= 0x01;
      expect(
        () => ArchivePlus.gunzip(badCrc),
        throwsA(isA<ArchiveChecksumException>()),
      );

      final badIsize = Uint8List.fromList(gz)..[gz.length - 1] ^= 0x01;
      expect(
        () => ArchivePlus.gunzip(badIsize),
        throwsA(isA<ArchiveChecksumException>()),
      );
    });

    test('supports dart:convert Stream transformation', () async {
      final source = utf8.encode('GZIP stream pipeline ' * 600);
      const codec = GZipPlusCodec();
      final encoded = await Stream<List<int>>.fromIterable(<List<int>>[
        source.sublist(0, 2048),
        source.sublist(2048),
      ]).transform(codec.encoder).toList();
      final decoded = await Stream<List<int>>.fromIterable(
        encoded,
      ).transform(codec.decoder).toList();
      expect(decoded.expand((c) => c).toList(), equals(source));
    });
  });
}
